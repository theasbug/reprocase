test('fresh-identity reproduction, secure comparison, export, localization and package import', async ({ page }) => {
  process.env.REPROCASE_HEADLESS = '1';
  const server = await createServer({ memory: true, port: 0 });
  const exceptions: string[] = [];
  page.on('pageerror', error => exceptions.push(error.message));
  try {
    await page.goto(server.url);
    await expect(page.getByTestId('load-demo')).toBeVisible();
    await page.getByTestId('load-demo').click();
    await expect(page.locator('.actor-card')).toHaveCount(2);
    await expect(page.locator('.connection-pill.connected')).toHaveCount(2);
    const sourceIdentity = await page.locator('.actor-card').first().locator('.actor-identity strong').first().innerText();
    const sourceRevision = await page.locator('.save-status').innerText();
    const approve = () => page.getByLabel('I approve this case version and the target origins above for this run.').check();
    await expect(page.getByTestId('run')).toBeDisabled();
    await approve();
    await page.getByTestId('run').click();
    await expect(page.getByRole('dialog', { name: 'Run preflight', exact: true })).toBeVisible();
    await page.getByTestId('confirm-run').click();
    await expect(page.locator('.verdict-banner h2')).toHaveText('Reproduced');
    await expect(page.locator('.execution-step.failed')).toHaveCount(0);
    await page.locator('.case-tabs').getByRole('button', { name: 'Investigation', exact: true }).click();
    await page.getByTestId('fresh-identities').click();
    await expect(page.locator('.actor-card').first().locator('.actor-identity strong').first()).not.toHaveText(sourceIdentity);
    await expect(page.locator('.save-status')).toHaveText(sourceRevision);
    await approve();
    await page.getByTestId('run').click();
    await expect(page.getByRole('dialog', { name: 'Run preflight', exact: true })).toBeVisible();
    await page.getByTestId('confirm-run').click();
    await expect(page.locator('.verdict-banner h2')).toHaveText('Reproduced');
    await expect(page.locator('.history-item')).toHaveCount(2);
    await page.locator('.case-tabs').getByRole('button', { name: 'Investigation', exact: true }).click();
    await mkdir(resolve('docs/screenshots'), { recursive: true });
    await page.setViewportSize({ width: 1440, height: 1520 });
    await page.screenshot({ path: resolve('docs/screenshots/workbench.png'), fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1050 });
    await page.getByTestId('secure-toggle').click();
    await expect(page.getByTestId('secure-toggle')).toContainText('Secure target');
    await approve();
    await page.getByTestId('run').click();
    await expect(page.getByRole('dialog', { name: 'Run preflight', exact: true })).toBeVisible();
    await page.getByTestId('confirm-run').click();
    await expect(page.locator('.verdict-banner h2')).toHaveText('Not reproduced');
    await page.getByRole('button', { name: 'Export case', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Review before sharing' })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Download package', exact: true })).toBeDisabled();
    await page.getByLabel('I have reviewed the contents for sensitive information.').check();
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download package', exact: true }).click();
    const downloaded = await downloadEvent;
    const packageText = await readFile((await downloaded.path())!, 'utf8');
    const exported = JSON.parse(packageText);
    expect(exported.format).toBe('reprocase');
    expect(exported.case.witness.success.length).toBeGreaterThan(0);
    expect(packageText).not.toContain('Bearer ');
    expect(packageText).not.toContain('rc_session=');
    expect(packageText).not.toContain(sourceIdentity);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Language', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'tr');
    await expect(page.locator('.case-tabs').getByRole('button', { name: 'Araştırma', exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Toggle color theme', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
    await page.getByRole('button', { name: 'Kanıt içe aktar', exact: true }).click();
    const importer = page.getByRole('dialog', { name: 'Kanıt içe aktar' });
    await importer.getByRole('button', { name: 'ReproCase paketi', exact: true }).click();
    await importer.locator('.code-input').fill(packageText);
    await importer.getByRole('button', { name: 'Taslak hazırla', exact: true }).click();
    await expect(importer).not.toBeVisible();
    await expect(page.locator('.case-link')).toHaveCount(2);
    const editor = page.getByRole('textbox', { name: 'JSON vaka tanımı', exact: true });
    await expect(editor).toBeVisible();
    const importedText = await editor.inputValue();
    expect(JSON.parse(importedText).id).not.toBe(exported.case.id);
    await editor.fill('{ invalid json');
    await expect(page.locator('.save-status')).toHaveClass(/error/);
    await expect(page.locator('.inline-error')).toBeVisible();
    await editor.fill(importedText);
    await expect(page.locator('.save-status')).toHaveClass(/saved/);
    await page.locator('.case-tabs').getByRole('button', { name: 'Araştırma', exact: true }).click();
    await expect(page.locator('.connection-pill.connected')).toHaveCount(0);
    await expect(page.locator('.case-heading')).toContainText(JSON.parse(importedText).title);
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByTestId('run')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    expect(exceptions).toEqual([]);
  } finally {
    await server.close();
  }
});

